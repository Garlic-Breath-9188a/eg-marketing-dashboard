#!/usr/bin/env python3
"""Generate .streamlit/secrets.toml for the Cloud Agent environment.

Streamlit reads credentials from .streamlit/secrets.toml, which is gitignored
and never committed. In a Cloud Agent VM there is no such file, so this script
materializes one from environment variables (the Cloud Agent "Secrets" panel
injects them as env vars).

Behavior:
  * DASHBOARD_PASSWORD falls back to "dev" so the password gate is usable even
    when no secret is configured, letting the app boot for development.
  * WORDPRESS_BASE_URL falls back to the project default.
  * Every other key is written only when a non-empty env var is present. This
    matters because ingest/refresh_all.py skips any source whose required
    secret is absent, so unset keys simply mean "that source stays empty"
    instead of erroring or hanging on failed API calls.

It is idempotent and safe to run on every boot.
"""
from __future__ import annotations

import os
from pathlib import Path

# Keys the app / ingest layer read from st.secrets. Optional keys are only
# emitted when the matching env var is set to a non-empty value.
OPTIONAL_KEYS = [
    "HUBSPOT_TOKEN",
    "HUBSPOT_PORTAL_ID",
    "AUTHOREDUP_API_KEY",
    "ASANA_ACCESS_TOKEN",
    "SLACK_TOKEN",
    "MS_CLIENT_ID",
    "MS_TENANT_ID",
    "MS_CLIENT_SECRET",
    "MS_REFRESH_TOKEN",
    "WORDPRESS_USER",
    "WORDPRESS_APP_PASSWORD",
    "WPCOM_API_TOKEN",
    "WPCOM_SITE",
]


def _toml_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    out_dir = repo_root / ".streamlit"
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "secrets.toml"

    lines: list[str] = [
        "# Auto-generated by .cursor/gen_secrets.py for the Cloud Agent environment.",
        "# Do not edit by hand: set values via the Cloud Agent Secrets panel instead.",
        "",
        f'DASHBOARD_PASSWORD = "{_toml_escape(os.environ.get("DASHBOARD_PASSWORD", "dev"))}"',
        f'WORDPRESS_BASE_URL = "{_toml_escape(os.environ.get("WORDPRESS_BASE_URL", "https://wealthtechtoday.com"))}"',
    ]

    for key in OPTIONAL_KEYS:
        value = os.environ.get(key, "").strip()
        if value:
            lines.append(f'{key} = "{_toml_escape(value)}"')

    out_path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out_path} ({len(lines)} lines).")


if __name__ == "__main__":
    main()
